namespace TaiwanAgri.Modules.Market.Entities.Enums
{
	/// <summary>
	/// 家禽行情原始價格欄位的解析結果狀態。
	/// 農業部四支家禽 API 的價格欄位型別是 string，除了正常數字外還混雜多種非數值寫法。
	/// 分類依據是 2026-08-24 對全歷史（2010/10/07 起、88236 個價格儲存格）的實測窮舉：
	/// 非數值共 12442 個、8 種相異字串，下列各狀態即對應實測到的語意分群。
	/// 前端畫圖時每個狀態都有明確的呈現方式，不需要自己再解析一次原始字串。
	/// </summary>
	public enum PriceStatus
	{
		/// <summary>成功解析為數字，Price 有值（唯一 Price 非 null 的狀態）</summary>
		Normal,

		/// <summary>原始值是空字串：該欄位當期不提供統計（實測 5426 次，幾乎全在雞蛋產地價）</summary>
		Empty,

		/// <summary>原始值是「休市」：當天無交易（實測 3585 次，四支來源都有）</summary>
		Closed,

		/// <summary>原始值是「-」：有交易但未報價（實測 3353 次，幾乎全在紅羽土雞南區）</summary>
		NotQuoted,

		/// <summary>原始值是「議價」：由買賣雙方議定，無公告價（實測 7 次，只出現在雞蛋大運輸價）</summary>
		Negotiated,

		/// <summary>
		/// 原始值是「41-42」這類區間報價：來源給的是價格區間而非單一價。
		/// 刻意不取中位數塞進 Price——那是我們自己發明來源沒說過的數字；
		/// 原始區間保留在 RawValue，要怎麼呈現交給前端決定（實測 70 次，全在紅羽土雞）
		/// </summary>
		RangeQuote,

		/// <summary>
		/// 不屬於以上任何一種的未知寫法，原始字串留在 RawValue 供事後檢視。
		/// 這個狀態的數量應該長期趨近於零；一旦在監控中看到它變多，代表來源出現了
		/// 新的表達方式，要回頭決定是否收編成正式狀態
		/// （實測僅 1 次：「31..8」，明顯是 31.8 的鍵入錯誤）
		/// </summary>
		Unrecognized
	}
}
