namespace TaiwanAgri.Modules.Weather.Constants
{
	/// <summary>
	/// 農藥劑型代碼（formCode）→ 中文劑型名稱的單一真相來源。
	///
	/// 為什麼是本地常數表而不是即時打第三支 API：農業部的 PesticideManualType 確實有中文劑型欄位，
	/// 但那份資料停留在 2014 年前、沒有任何狀態欄位，且與許可證主檔對同一產品的劑型記載會互相矛盾
	/// （亞滅培「日曹強必勇」許可證寫 SG、手冊寫「水溶性粉劑」＝SP）。逐次查詢會把已知有錯的資料
	/// 直接餵進正式回應；改成離線把它當「字典」用一次、人工核對後固定下來，錯誤就止於此處。
	///
	/// **這張表的每一列都有實測佐證，不是照國際標準代碼表填的**（2026-08-22 探勘 → 2026-08-23 重建）：
	/// 先掃 5246 張相異許可證統計實際出現過的 formCode（共 29 種），再用商品名把許可證接回
	/// 農藥名稱手冊做多數決，取得代碼對應的中文名。這個步驟推翻了初版三個「照 FAO／CIPAC 標準填」
	/// 的項目——農業部有自己的中文譯名慣例，與國際標準的字面直譯不同：
	///   TB → 官方用「片劑」，不是「錠劑」
	///   CS → 官方用「膠囊懸著劑」，不是「微囊懸浮劑」
	///   FS → 官方用「種子處理用水懸劑」，不是「種子處理懸浮劑」
	/// 同時補回初版漏掉、但實際出現 41 次的 UL，並刪掉初版填了卻在 5246 張樣本中一次都沒出現的
	/// 8 個代碼（AE／DS／FU／GB／ME／TC／TK／WS）。
	/// **教訓：「這是國際標準代碼」不等於「這個資料集用的就是那套譯名」，仍然要對著真實資料查證。**
	///
	/// 查無對應時 <see cref="ToChineseName"/> 直接回傳原始代碼字串（fallback），
	/// 不會因為漏收錄某個代碼就讓整支功能壞掉或顯示空白。
	/// </summary>
	public static class PesticideForms
	{
		private static readonly Dictionary<string, string> _map = new(StringComparer.OrdinalIgnoreCase)
		{
			// 括號內為「手冊佐證票數／可比對筆數」，票數高者為多數決結果
			{ "EC", "乳劑" },                  // 317/338，樣本 1348 張，最常見
			{ "WP", "可溼性粉劑" },            // 228/242，樣本 887 張
			{ "SC", "水懸劑" },                // 99/107，樣本 567 張
			{ "SL", "溶液" },                  // 105/115，樣本 533 張
			{ "GR", "粒劑" },                  // 81/86，樣本 273 張
			{ "SP", "水溶性粉劑" },            // 36/41，樣本 164 張
			{ "WG", "水分散性粒劑" },          // 20/23，樣本 129 張
			{ "DP", "粉劑" },                  // 11/17，樣本 93 張
			{ "SG", "水溶性粒劑" },            // 6/7，樣本 76 張
			{ "UL", "超低容量液劑" },          // 定向查證 3 筆一致，樣本 41 張（初版漏收）
			{ "EW", "水基乳劑" },              // 8/8，樣本 35 張
			{ "TB", "片劑" },                  // 定向查證（含量 10% 對上「片劑」），樣本 15 張
			{ "RB", "餌劑" },                  // 2/2，樣本 13 張
			{ "CS", "膠囊懸著劑" },            // 2/2，樣本 7 張
			{ "ZC", "膠囊水懸混劑" },          // 定向查證 1 筆，樣本 7 張
			{ "AL", "其他液劑" },              // 定向查證 1 筆，樣本 6 張
			{ "SE", "水懸乳劑" },              // ⚠ 無手冊佐證，樣本 5 張——見下方說明
			{ "PA", "糊狀劑" },                // 定向查證 1 筆，且同組商品名多為「膏」，樣本 4 張
			{ "FS", "種子處理用水懸劑" },      // 定向查證 1 筆，樣本 3 張
			{ "ST", "水溶性片劑" },            // 定向查證 1 筆，樣本 2 張

			// ⚠ SE 是唯一保留但無直接佐證的一列：5 張樣本的商品名在手冊全部查無。
			// 保留的理由是它與已查證的 SC（水懸劑）／EW（水基乳劑）同屬一組命名體系、
			// 且中文農藥文獻用法一致；風險是若判斷錯誤會顯示錯誤劑型。
			// 日後若查到官方對照表，這一列要優先回頭核對。
			//
			// 以下代碼在樣本中出現但無法取得中文名，刻意不猜、走 fallback 顯示原始代碼：
			//   DC（2 張）／OD（2 張）／OF（2 張）／AP（2 張）／GS（1 張）／XX（1 張）／SR（1 張）
			// 另有 SPSB（1 張，農藥製03330 納乃得「地虎」）看起來是資料輸入錯誤
			// （像是 SP 與 SB 黏在一起），同樣走 fallback。
		};

		/// <summary>
		/// 代碼轉中文名。查無對應時回傳原始代碼；代碼為空時回傳「原體」——
		/// 實測 5246 張樣本中 formCode 為空的 1026 張全部是原體許可證（農藥原製／農藥原進）。
		/// </summary>
		public static string ToChineseName(string? formCode)
		{
			if (string.IsNullOrWhiteSpace(formCode)) return "原體";

			var key = formCode.Trim();
			return _map.TryGetValue(key, out var name) ? name : key;
		}
	}
}
